describe("D3 workflow script injection is decided on the parsed YAML", () => {
  const ruleSet = loadRules(RULES_DIR);
  const HEAD = ["on: issues", "jobs:", "  a:", "    runs-on: ubuntu-latest"];
  const TITLE = "${{ github.event.issue.title }}";
  let counter = 0;
  const scanWorkflow = (lines: string[]) => {
    counter += 1;
    const root = path.join(temp, `wf-${counter}`);
    writeFile(root, ".github/workflows/w.yml", `${lines.join("\n")}\n`);
    const result = scanRules(inventory(root).files, ruleSet, { inlineIgnore: false });
    return {
      hits: result.hits
        // The expression-injection rules only; the other gha-* rules (permissions,
        // pinning, ...) have their own tests in rules-iac.test.ts.
        .filter((hit) => hit.rule.group === "gha-expression-injection")
        .map((hit) => `${hit.line} ${hit.rule.id}`)
        .sort((a, b) => Number.parseInt(a, 10) - Number.parseInt(b, 10)),
      warnings: result.warnings,
    };
  };

  // Every shape is valid YAML that GitHub runs; each was missed by the
  // line-based `withinKeys` and is reported on the line that holds the
  // expression (for an alias: where the script text is written).
  const cases: Array<[string, string[], string[]]> = [
    ["plain scalar", [...HEAD, "    steps:", `      - run: echo ${TITLE}`], ["6 gha-script-injection"]],
    ["alias in a flow mapping", ["x-defs:", `  c: &cmd "echo ${TITLE}"`, ...HEAD, "    steps:", "      - { run: *cmd }"], ["2 gha-script-injection"]],
    ["alias on the next line", ["x-defs:", `  c: &cmd "echo ${TITLE}"`, ...HEAD, "    steps:", "      - run:", "          *cmd"], ["2 gha-script-injection"]],
    ["anchor on the key", [...HEAD, "    steps:", `      - &k run: echo ${TITLE}`], ["6 gha-script-injection"]],
    ["tag on the key", [...HEAD, "    steps:", `      - !!str run: echo ${TITLE}`], ["6 gha-script-injection"]],
    ["escaped quoted key", [...HEAD, "    steps:", `      - "r\\u0075n": echo ${TITLE}`], ["6 gha-script-injection"]],
    [
      "flow sequence with a continued scalar",
      [...HEAD, "    steps: [", '          { run: "echo', `     ${TITLE}" }`, "    ]"],
      ["7 gha-script-injection"],
    ],
    [
      "workflow-level env, then ${{ env.X }}",
      ["env:", `  T2: ${TITLE}`, ...HEAD, "    steps:", "      - env:", "          T: x", "        run: echo ${{ env.T2 }}"],
      ["10 gha-script-injection"],
    ],
    [
      "job-level env",
      [...HEAD, "    env:", `      T2: ${TITLE}`, "    steps:", "      - run: echo ${{ env.T2 }}"],
      ["8 gha-script-injection"],
    ],
    [
      "step-level env, bracket notation",
      [...HEAD, "    steps:", "      - env:", `          T2: ${TITLE}`, "        run: echo ${{ env['T2'] }}"],
      ["8 gha-script-injection"],
    ],
    [
      "matrix value",
      [...HEAD, "    strategy:", "      matrix:", `        cmd: ["echo ${TITLE}"]`, "    steps:", "      - run: ${{ matrix.cmd }}"],
      ["9 gha-script-injection"],
    ],
    [
      "matrix include",
      [...HEAD, "    strategy:", "      matrix:", "        include:", `          - cmd: echo ${TITLE}`, "    steps:", "      - run: ${{ matrix.cmd }}"],
      ["10 gha-script-injection"],
    ],
    ["bracket notation", [...HEAD, "    steps:", "      - run: echo ${{ github['event']['issue']['title'] }}"], ["6 gha-script-injection"]],
    ["upper case", [...HEAD, "    steps:", "      - run: echo ${{ GITHUB.EVENT.ISSUE.TITLE }}"], ["6 gha-script-injection"]],
    [
      "expression split across lines",
      [...HEAD, "    steps:", "      - run: |", "          echo ${{", "            github.event.issue.title }}"],
      ["7 gha-script-injection"],
    ],
    [
      "block scalar reports the line of the expression",
      [...HEAD, "    steps:", "      - run: |", "          echo one", "", `          echo ${TITLE}`],
      ["9 gha-script-injection"],
    ],
    ["explicit key", [...HEAD, "    steps:", "      - ? run", `        : echo ${TITLE}`], ["7 gha-script-injection"]],
    [
      "script input of github-script",
      [...HEAD, "    steps:", "      - uses: actions/github-script@v7", "        with:", `          script: console.log("${TITLE}")`],
      ["8 gha-script-injection"],
    ],
  ];
  for (const [name, lines, expected] of cases) {
    it(`reports: ${name}`, () => {
      const result = scanWorkflow(lines);
      expect(result.hits).toEqual(expected);
      expect(result.warnings).toEqual([]);
    });
  }

  it("does not report expressions that are passed as data", () => {
    const result = scanWorkflow([
      "on: pull_request",
      "concurrency: ${{ github.head_ref }}",
      "env:",
      `  TITLE: ${TITLE}`,
      "jobs:",
      "  a:",
      "    concurrency:",
      "      group: ${{ github.workflow }}-${{ github.event.pull_request.title }}",
      "    strategy:",
      "      matrix:",
      "        os: [ubuntu-latest]",
      `        note: ["${TITLE}"]`,
      "    steps:",
      "      - uses: actions/checkout@v4",
      "        with:",
      "          ref: ${{ github.event.pull_request.head.ref }}",
      // The documented fix: the shell receives the variable as data.
      '      - run: echo "$TITLE" "${TITLE}" ${{ matrix.os }} ${{ env.OTHER }}',
      "        env:",
      "          BODY: ${{ github.event.pull_request.body }}",
      '      - run: gh issue close "$BODY"',
    ]);
    expect(result.hits).toEqual([]);
    expect(result.warnings).toEqual([]);
  });

  it("fails open with a warning when the file cannot be parsed", () => {
    // Invalid YAML: every attacker-controlled expression in the file is
    // reported, wherever it is written.
    const invalid = scanWorkflow([
      "on: issues",
      "jobs:",
      "  a:",
      "    steps:",
      "      - uses: x/y@v1",
      "        with:",
      `          title: ${TITLE}`,
      "      - run: |",
      "# dedented comment",
      `          echo ${TITLE}`,
    ]);
    expect(invalid.hits).toEqual(["7 gha-script-injection", "10 gha-script-injection"]);
    expect(invalid.warnings.join("\n")).toMatch(/w\.yml: not valid YAML .*matched against every line/);
    // The fallback sees the same canonical form: bracket notation, upper
    // case and an expression split across lines are not a way around it.
    const evasive = scanWorkflow([
      "on: issues",
      "jobs:",
      "  a:",
      "    steps:",
      "      - run: |",
      "# dedented comment",
      "          echo ${{ github['event']['issue']['title'] }}",
      "          echo ${{ GITHUB.EVENT.COMMENT.BODY }}",
      "          echo ${{",
      "            github.event.issue.body }}",
    ]);
    expect(evasive.hits).toEqual(["7 gha-script-injection", "8 gha-script-injection", "9 gha-script-injection"]);
    expect(evasive.warnings.join("\n")).toMatch(/matched against every line/);
  });

  it("is bounded: alias bombs and oversized files fall back instead of expanding", () => {
    // Billion laughs: nine levels of nine aliases each.
    const bomb = ["a0: &a0 { run: x }"];
    for (let level = 1; level <= 9; level += 1) {
      bomb.push(`a${level}: &a${level} [${Array(9).fill(`*a${level - 1}`).join(", ")}]`);
    }
    bomb.push("on: issues", "jobs:", "  a:", "    steps:", `      - run: echo ${TITLE}`, "      - with: *a9");
    const started = Date.now();
    const parsed = yamlKeyValues(bomb.join("\n"), ["run"]);
    expect(Date.now() - started).toBeLessThan(5_000);
    expect(parsed).toMatchObject({ ok: false });
    const result = scanWorkflow(bomb);
    expect(result.hits).toEqual([`${bomb.length - 1} gha-script-injection`]);
    expect(result.warnings.join("\n")).toMatch(/nodes after alias expansion|nested/);

    const big = `# ${"x".repeat(YAML_VALUES_MAX_BYTES)}\non: issues\n`;
    expect(yamlKeyValues(big, ["run"])).toMatchObject({ ok: false });
    expect(yamlKeyValues("a: [1, 2", ["run"])).toMatchObject({ ok: false });
    expect(yamlKeyValues("a: *missing", ["run"])).toMatchObject({ ok: false });
    expect(yamlKeyValues("", ["run"])).toEqual({ ok: true, values: [] });
  });

  it("normalises expressions and maps offsets back to lines", () => {
    expect(normalizeExpression(" GitHub [ 'event' ] . issue\n  .Title ")).toBe("github.event.issue.title");
    const parsed = yamlKeyValues(["steps:", "  - run: |", "      one", "      two ${{ a.b }}", "    name: x"].join("\n"), ["run"]);
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    expect(parsed.values).toHaveLength(1);
    const value = parsed.values[0];
    expect(value?.text).toBe("one\ntwo ${{ a.b }}\n");
    expect(value?.lineAt(0)).toBe(2);
    expect(value?.lineAt(value.text.indexOf("${{"))).toBe(3);
  });
});

