describe("D2 path context cannot silently empty the exit code", () => {
  it("a generated-file header is recorded and lowers nothing (review case n1)", async () => {
    const root = path.join(temp, "header");
    writeFile(root, "src/handlers.py", `# @generated by codegen, DO NOT EDIT\n${PYTHON_EVAL}`);
    writeFile(root, "src/creds.py", `# Code generated by tool. DO NOT EDIT.\nAWS = "${AWS_KEY}"\npassword = "Tr0ub4dor&3xyzQ"\n`);
    writeFile(root, "src/medium.py", `# @generated\n${PYTHON_MEDIUM}`);
    expect(classifyFileDetailed("src/handlers.py", "# @generated\nx = 1\n", "python")).toEqual({
      context: "generated",
      source: "header",
    });
    expect(classifyFileDetailed("app/x_pb2.py", "x = 1\n", "python")).toEqual({ context: "generated", source: "path" });
    // The path wins over the header: a test file stays a test file.
    expect(classifyFileDetailed("tests/a.py", "# @generated\n", "python")).toEqual({ context: "test", source: "path" });

    const result = await scan(root, "header");
    expect(result.findings.length).toBeGreaterThanOrEqual(3);
    for (const finding of result.findings) {
      expect([finding.file, finding.pathContext]).toEqual([finding.file, "generated"]);
      expect(finding.confidenceOriginal).toBeUndefined();
      expect(finding.adjustments).toBeUndefined();
    }
    expect(result.summary.confidenceLowered.total).toBe(0);
    expect(result.summary.reductions.demoted.total).toBe(0);
    expect(result.summary.exitCode.code).toBe(1);
    expect(result.summary.exitCode.counting).toBe(
      result.findings.filter((finding) => finding.severity === "critical" || finding.severity === "high").length,
    );
  });

  it("a generated or vendored path still lowers, except for what is dangerous anywhere", () => {
    const base = (init: Partial<Parameters<typeof createFinding>[0]> = {}): Finding =>
      createFinding({
        ruleId: "py-weak-hash",
        title: "t",
        category: "sast",
        severity: "high",
        confidence: "medium",
        file: "src/a.py",
        startLine: 1,
        evidence: "x",
        remediation: "r",
        provenance: { engine: "builtin-rules" },
        ...init,
      });
    const inPath = (finding: Finding, file: string): Finding =>
      applyPathContext({ ...finding, file }, undefined);
    expect(inPath(base(), "node_modules/x/a.py").confidence).toBe("low");
    expect(inPath(base(), "lib/app.min.js").confidence).toBe("low");
    expect(inPath(base(), "proto/a_pb2.py").confidence).toBe("low");
    expect(inPath(base(), "tests/a.py").confidence).toBe("low");
    expect(inPath(base({ confidence: "high" }), "tests/a.py").confidence).toBe("medium");
    // Header only: tagged, not lowered.
    const header = applyPathContext(base(), { pathContext: "generated", pathContextSource: "header", kind: "source" });
    expect([header.pathContext, header.confidence, header.adjustments]).toEqual(["generated", "medium", undefined]);

    const kept: Array<[string, Finding]> = [
      ["critical-high-confidence", base({ severity: "critical", confidence: "high" })],
      ["format-credential", base({ ruleId: "secret-private-key", category: "secrets", severity: "critical", confidence: "medium" })],
      ["format-credential", base({ ruleId: "secret-url-credentials", category: "secrets", confidence: "high" })],
      ["format-credential", base({ ruleId: "gitleaks-private-key", category: "secrets", confidence: "high" })],
      ["provider-credential", base({ ruleId: "secret-github-token", category: "secrets", confidence: "high" })],
    ];
    for (const [reason, finding] of kept) {
      for (const file of ["tests/a.py", "vendor/a.py", "docs/a.md", "demo/a.py", "spec/a_test.go", "lib/a.min.js"]) {
        expect([finding.ruleId, file, pathContextExemption({ ...finding, file }, undefined)]).toEqual([finding.ruleId, file, reason]);
        const applied = inPath(finding, file);
        expect(applied.confidence).toBe(finding.confidence);
        expect(applied.adjustments).toBeUndefined();
        expect(applied.pathContext).toBeDefined();
      }
    }
    // A critical finding of a medium-confidence rule is not exempt.
    expect(pathContextExemption(base({ severity: "critical" }), undefined)).toBeUndefined();
    expect(pathContextExemption({ ...base(), file: ".github/workflows/a.yml" }, undefined)).toBe("ci-file");
    expect(pathContextExemption({ ...base(), file: "tests/Dockerfile" }, undefined)).toBe("dockerfile");
    expect(pathContextExemption({ ...base(), file: "tests/AGENTS.md" }, undefined)).toBe("agent-instruction-file");
    expect(pathContextExemption({ ...base(), category: "sca", file: "tests/requirements.txt" }, undefined)).toBe("dependency-manifest");
  });

  it("warns with counts and the flag, everywhere, whenever a finding leaves the exit-code set (review case h1)", async () => {
    // One ordinary source file and five files whose names say "test": well
    // below the old "more than half of the source files" trigger is not
    // required any more; the warning is unconditional.
    const root = path.join(temp, "names");
    for (let index = 0; index < 8; index += 1) writeFile(root, `src/mod${index}.py`, "x = 1\n");
    writeFile(root, "src/test_x.py", PYTHON_MEDIUM);
    writeFile(root, "src/conftest.py", PYTHON_MEDIUM);
    writeFile(root, "demo/app.py", PYTHON_MEDIUM);
    writeFile(root, "doc/app.py", PYTHON_MEDIUM);
    writeFile(root, "tests/key.pem", `-----BEGIN ${"RSA"} PRIVATE KEY-----\nMIIB\n-----END RSA PRIVATE KEY-----\n`);
    writeFile(root, "tests/app.py", PYTHON_EVAL);

    const reference = await scan(root, "names-include", { includeTests: true });
    const mediumRule = reference.findings.filter((finding) => finding.file === "src/test_x.py");
    expect(mediumRule.length).toBeGreaterThan(0);
    expect(mediumRule.every((finding) => finding.confidence === "medium")).toBe(true);
    expect(reference.summary.reductions.demoted.total).toBe(0);
    expect(reductionWarnings(reference.summary)).toEqual([]);

    const result = await scan(root, "names");
    const demoted = result.findings.filter((finding) => finding.adjustments?.some((reason) => reason.startsWith("path-context:")));
    expect(demoted.length).toBe(mediumRule.length * 4);
    // The private key and the critical eval in tests/ keep their confidence.
    expect(result.findings.find((finding) => finding.ruleId === "secret-private-key")?.confidence).toBe("high");
    expect(result.findings.filter((finding) => finding.file === "tests/app.py" && finding.severity === "critical").every((finding) => finding.confidence === "high")).toBe(true);
    expect(result.summary.reductions.demoted).toMatchObject({ total: demoted.length, pathContext: demoted.length, placeholder: 0 });
    expect(reference.summary.exitCode.counting - result.summary.exitCode.counting).toBe(demoted.length);
    // The old warning needed more than half of the source files to be affected.
    expect(result.warnings.join("\n")).not.toMatch(/source files are classified/);

    const expected = new RegExp(
      `WARNING:?\\*{0,2} ${demoted.length} finding\\(s\\) at severity ≥ high do not count toward the exit code .*path context .* ${demoted.length}, off with \`?--include-tests\`?.*\`?--untrusted\`?`,
    );
    expect(renderSummaryText(result.summary).join("\n")).toMatch(expected);
    expect(renderHeadlineMarkdown(result.summary).join("\n")).toMatch(expected);
    expect(report(result.runDir).split("## 2.")[0]).toMatch(expected);
    expect(renderStepSummaryMarkdown({ summary: result.summary, reportPaths: [] })).toMatch(expected);
    expect(renderHeadlineMarkdown(result.summary, "zh").join("\n")).toContain("--include-tests");

    // The same through the CLI: plain summary and --ci.
    const plain = cli(["scan", root, "--offline", "--no-external", "--out", path.join(temp, "out-names-cli")]);
    expect(plain.stdout).toMatch(expected);
    const ci = cli(["scan", root, "--offline", "--no-external", "--ci", "--out", path.join(temp, "out-names-ci")]);
    expect(ci.stdout).toMatch(expected);
    const off = cli(["scan", root, "--offline", "--no-external", "--include-tests", "--out", path.join(temp, "out-names-off")]);
    expect(off.stdout).not.toContain("WARNING");
  });

  it("counts dev-dependency and placeholder demotions in the same warning", () => {
    const make = (init: Partial<Parameters<typeof createFinding>[0]>): Finding =>
      createFinding({
        ruleId: "r",
        title: "t",
        category: "sast",
        severity: "high",
        confidence: "high",
        file: "a.py",
        startLine: 1,
        evidence: Math.random().toString(),
        remediation: "r",
        provenance: { engine: "builtin-rules" },
        ...init,
      });
    const findings = [
      lowerConfidence(make({ category: "sca", dependencyScope: "dev" }), "dev-dependency", "low"),
      lowerConfidence(make({ category: "secrets" }), "placeholder-value", "low"),
      lowerConfidence(make({}), "path-context:test", "low"),
      // Below --fail-on: lowered, but it would not have counted anyway.
      lowerConfidence(make({ severity: "medium" }), "path-context:test", "low"),
      // Lowered but still at the threshold: still counted, no warning.
      lowerConfidence(make({}), "path-context:test", "step"),
      make({}),
    ];
    const summary = summarizeFindings(findings);
    expect(summary.reductions.demoted).toEqual({
      total: 3,
      pathContext: 1,
      placeholder: 1,
      devDependency: 1,
      optionalDependency: 0,
      other: 0,
    });
    expect(summary.exitCode.counting).toBe(2);
    const [warning] = reductionWarnings(summary);
    expect(warning).toContain("3 finding(s) at severity ≥ high");
    expect(warning).toContain("`--include-tests`");
    expect(warning).toContain("`--include-dev`");
    expect(warning).toContain("`--include-placeholders`");
    expect(renderSummaryText(summary).filter((line) => line.startsWith("WARNING: "))).toHaveLength(1);
  });
});

