describe("confidence adjustments on a finding", () => {
  const base = (): Finding =>
    createFinding({
      ruleId: "py-example",
      title: "t",
      category: "sast",
      severity: "high",
      confidence: "high",
      file: "tests/test_app.py",
      startLine: 1,
      evidence: "x",
      remediation: "r",
      provenance: { engine: "builtin-rules" },
    });

  it("lowers one step or to low, records why, and never past low", () => {
    const once = lowerConfidence(base(), "path-context:test", "step");
    expect(once.confidence).toBe("medium");
    expect(once.confidenceOriginal).toBe("high");
    expect(once.adjustments).toEqual(["path-context:test"]);
    const twice = lowerConfidence(once, "dev-dependency", "step");
    expect(twice.confidence).toBe("low");
    expect(twice.confidenceOriginal).toBe("high");
    expect(twice.adjustments).toEqual(["path-context:test", "dev-dependency"]);
    // No effect, no record.
    const third = lowerConfidence(twice, "placeholder-value", "low");
    expect(third).toBe(twice);
    expect(lowerConfidence(base(), "placeholder-value", "low").confidence).toBe("low");
    const restored = restoreConfidence(twice);
    expect(restored.confidence).toBe("high");
    expect(restored.confidenceOriginal).toBeUndefined();
    expect(restored.adjustments).toBeUndefined();
    // The adjusted shape is valid for the finding schema.
    expect(FindingSchema.parse(twice).adjustments).toEqual(["path-context:test", "dev-dependency"]);
  });

  it("applies the path context with the documented effect per class", () => {
    const at = (file: string, context?: Finding["pathContext"]): Finding =>
      applyPathContext({ ...base(), file }, context ? { pathContext: context, kind: "source" } : undefined);
    expect(at("tests/a.py").confidence).toBe("medium");
    expect(at("docs/a.py").adjustments).toEqual(["path-context:docs"]);
    expect(at("examples/a.py").confidence).toBe("medium");
    expect(at("vendor/a.py").confidence).toBe("low");
    expect(at("dist/a.js").confidence).toBe("low");
    expect(at("src/a.py", "generated").adjustments).toEqual(["path-context:generated"]);
    const ordinary = at("src/a.py");
    expect(ordinary.pathContext).toBeUndefined();
    expect(ordinary.confidenceOriginal).toBeUndefined();
    // --include-tests: recorded, not lowered.
    const included = applyPathContext({ ...base(), file: "tests/a.py" }, undefined, { includeTests: true });
    expect(included.pathContext).toBe("test");
    expect(included.confidence).toBe("high");
    expect(included.adjustments).toBeUndefined();
  });
});

describe("path context in a scan", () => {
  const root = path.join(temp, "layout");
  const awsKey = fake(["AKIA", "QRSTUVWX", "YZ234567"]);
  writeFile(root, "src/app.py", PYTHON_APP);
  writeFile(root, "tests/test_app.py", PYTHON_APP);
  writeFile(root, "docs/snippet.py", PYTHON_APP);
  writeFile(root, "examples/app.py", PYTHON_APP);
  writeFile(root, "third_party/lib/app.py", PYTHON_APP);
  writeFile(root, "src/generated_api.py", `# Generated by apigen 1.2. DO NOT EDIT.\n${PYTHON_APP}`);
  writeFile(root, "tests/Dockerfile", "FROM ubuntu:22.04\nRUN make\n");
  writeFile(root, "tests/data/keys.txt", `aws_access_key_id = ${awsKey}\n`);
  writeFile(
    root,
    "tests/.github/workflows/ci.yml",
    'on: pull_request_target\njobs:\n  b:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - run: echo "${{ github.event.pull_request.title }}"\n',
  );
  writeFile(root, "README.md", 'Use `password = "Tr0ub4dor&3-horse-staple"` to log in.\n');

  const scan = (name: string, extra: { includeTests?: boolean } = {}) =>
    scanProject({
      root,
      out: path.join(temp, name),
      offline: true,
      engines: ["builtin"],
      noIgnoreFile: true,
      noBaseline: true,
      formats: ["json"],
      ...extra,
    });

  it("lowers confidence by class, records the context and drops nothing", async () => {
    const lowered = await scan("layout-out");
    const reference = await scan("layout-out-include", { includeTests: true });

    // Same results either way: nothing is dropped, nothing changes identity.
    const key = (finding: Finding): string => `${finding.kind}:${finding.file}:${finding.startLine}:${finding.ruleId}`;
    const all = [...lowered.findings, ...lowered.hotspots];
    const referenceAll = [...reference.findings, ...reference.hotspots];
    expect(all.map(key).sort()).toEqual(referenceAll.map(key).sort());
    expect(all.map((finding) => finding.fingerprint).sort()).toEqual(
      referenceAll.map((finding) => finding.fingerprint).sort(),
    );
    const referenceByKey = new Map(referenceAll.map((finding) => [key(finding), finding]));

    const expectedContext: Record<string, string | undefined> = {
      "src/app.py": undefined,
      "tests/test_app.py": "test",
      "docs/snippet.py": "docs",
      "examples/app.py": "example",
      "third_party/lib/app.py": "vendored",
      "src/generated_api.py": "generated",
      "README.md": "docs",
    };
    const seen = new Set<string>();
    for (const finding of all) {
      const original = referenceByKey.get(key(finding)) as Finding;
      // With --include-tests the context is recorded and nothing is lowered.
      expect(original.confidenceOriginal).toBeUndefined();
      expect(original.adjustments).toBeUndefined();
      expect(original.pathContext).toBe(finding.pathContext);
      if (!(finding.file in expectedContext)) continue;
      seen.add(finding.file);
      const context = expectedContext[finding.file];
      expect([finding.file, finding.pathContext]).toEqual([finding.file, context]);
      // Not lowered: ordinary source, a file that is "generated" only by its
      // header comment (free for an attacker to write), and a critical
      // finding the rule reports with high confidence.
      const kept =
        context === undefined ||
        finding.file === "src/generated_api.py" ||
        (original.severity === "critical" && original.confidence === "high");
      const expected = kept
        ? original.confidence
        : context === "vendored" || context === "generated"
          ? "low"
          : step(original.confidence);
      expect([key(finding), finding.confidence]).toEqual([key(finding), expected]);
      if (expected === original.confidence) {
        expect(finding.confidenceOriginal).toBeUndefined();
        expect(finding.adjustments).toBeUndefined();
      } else {
        expect(finding.confidenceOriginal).toBe(original.confidence);
        expect(finding.adjustments).toEqual([`path-context:${context}`]);
        expect(CONFIDENCE_ORDER[finding.confidence]).toBeLessThan(CONFIDENCE_ORDER[original.confidence]);
      }
    }
    expect([...seen].sort()).toEqual(Object.keys(expectedContext).sort());
    // The fixture has high- and medium-confidence findings in each copy.
    const inTests = lowered.findings.filter((finding) => finding.file === "tests/test_app.py");
    expect(inTests.some((finding) => finding.confidence === "high" && finding.severity === "critical")).toBe(true);
    // A header comment alone lowers nothing.
    const generated = lowered.findings.filter((finding) => finding.file === "src/generated_api.py");
    expect(generated.length).toBeGreaterThan(0);
    expect(generated.every((finding) => finding.pathContext === "generated" && finding.adjustments === undefined)).toBe(true);
    expect(inTests.some((finding) => finding.confidenceOriginal === "medium")).toBe(true);
  });

  it("keeps full confidence for provider credentials, CI files and Dockerfiles", async () => {
    const result = await scan("layout-out-exempt");
    const aws = result.findings.find((finding) => finding.ruleId === "secret-aws-access-key");
    expect(aws?.file).toBe("tests/data/keys.txt");
    expect(aws?.pathContext).toBe("test");
    expect(aws?.confidence).toBe("high");
    expect(aws?.adjustments).toBeUndefined();
    const docker = result.findings.filter((finding) => finding.file === "tests/Dockerfile");
    expect(docker.length).toBeGreaterThan(0);
    for (const finding of docker) {
      expect(finding.pathContext).toBe("test");
      expect(finding.confidenceOriginal).toBeUndefined();
    }
    const workflow = result.findings.filter((finding) => finding.file === "tests/.github/workflows/ci.yml");
    // gha-pull-request-target is a hotspot (a base-branch checkout is the
    // documented safe use); the finding here is the script injection.
    expect(workflow.map((finding) => finding.ruleId).sort()).toEqual(["gha-script-injection"]);
    for (const finding of workflow) {
      expect(finding.confidence).toBe("high");
      expect(finding.adjustments).toBeUndefined();
    }
  });

  it("reports the effect in run.json, findings.json and coverage.json", async () => {
    const result = await scan("layout-out-counts");
    const run = JSON.parse(fs.readFileSync(path.join(result.runDir, "run.json"), "utf8")) as {
      args: { includeTests: boolean; includeDev: boolean };
      pathContext: Record<string, number>;
      adjustments: Record<string, number>;
    };
    expect(run.args.includeTests).toBe(false);
    expect(run.args.includeDev).toBe(false);
    expect(Object.keys(run.pathContext).sort()).toEqual([
      "docs",
      "example",
      "generated",
      "lowered",
      "test",
      "vendored",
    ]);
    const count = (context: string): number =>
      result.findings.filter((finding) => finding.pathContext === context).length;
    for (const context of ["test", "docs", "example", "vendored", "generated"]) {
      expect(run.pathContext[context]).toBe(count(context));
      expect(run.pathContext[context]).toBeGreaterThan(0);
    }
    const lowered = result.findings.filter((finding) =>
      finding.adjustments?.some((reason) => reason.startsWith("path-context:")),
    ).length;
    expect(run.pathContext.lowered).toBe(lowered);
    expect(lowered).toBeGreaterThan(0);
    expect(lowered).toBeLessThan(
      ["test", "docs", "example", "vendored", "generated"].reduce((sum, context) => sum + count(context), 0),
    );
    expect(run.adjustments["path-context:test"]).toBeGreaterThan(0);

    const envelope = JSON.parse(fs.readFileSync(path.join(result.runDir, "findings.json"), "utf8")) as {
      run: { pathContext: Record<string, number> };
      findings: Finding[];
    };
    expect(envelope.run.pathContext).toEqual(run.pathContext);
    expect(envelope.findings.some((finding) => finding.confidenceOriginal !== undefined)).toBe(true);

    const coverage = JSON.parse(fs.readFileSync(path.join(result.runDir, "coverage.json"), "utf8")) as {
      scannedFiles: Array<{ path: string; pathContext?: string }>;
      pathContext: { lowering: boolean; files: Record<string, number> };
    };
    const byPath = new Map(coverage.scannedFiles.map((file) => [file.path, file.pathContext]));
    expect(byPath.get("src/app.py")).toBeUndefined();
    expect(byPath.get("tests/test_app.py")).toBe("test");
    expect(byPath.get("README.md")).toBe("docs");
    expect(byPath.get("examples/app.py")).toBe("example");
    expect(byPath.get("third_party/lib/app.py")).toBe("vendored");
    expect(byPath.get("src/generated_api.py")).toBe("generated");
    expect(coverage.pathContext.lowering).toBe(true);
    expect(coverage.pathContext.files.test).toBe(4);

    // More than half of the source files are in a lowered class: said out loud.
    expect(result.warnings.join("\n")).toMatch(
      /5 of 6 source files are classified as test, docs, example, vendored or generated/,
    );
    const included = await scan("layout-out-counts-include", { includeTests: true });
    expect(included.warnings.join("\n")).not.toMatch(/source files are classified/);
    expect((included.run as { pathContext: { lowered: number; test: number } }).pathContext.lowered).toBe(0);
    expect((included.run as { pathContext: { lowered: number; test: number } }).pathContext.test).toBe(
      run.pathContext.test,
    );
    expect(included.coverage.pathContext?.lowering).toBe(false);
  });

  it("inventories the path context of each file", () => {
    const files = new Map(inventory(root).files.map((file) => [file.relPath, file.pathContext]));
    expect(files.get("src/app.py")).toBeUndefined();
    expect(files.get("tests/Dockerfile")).toBe("test");
    expect(files.get("src/generated_api.py")).toBe("generated");
  });
});

describe("dev dependencies", () => {
  const client: HttpClient = {
    async postJson(_url, body) {
      const queries = (body as { queries: unknown[] }).queries;
      return { results: queries.map(() => ({ vulns: [{ id: "GHSA-test-0001" }] })) };
    },
    async getJson() {
      return {
        id: "GHSA-test-0001",
        summary: "Test advisory",
        severity: [{ type: "CVSS_V3", score: "CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H" }],
        affected: [{ ranges: [{ events: [{ fixed: "9.9.9" }] }] }],
      };
    },
  };
  const root = path.join(temp, "devdeps");
  // The lockfile sits under tests/: dependency manifests are exempt from the
  // path context, so only the dev scope may lower the confidence.
  writeFile(
    root,
    "tests/Pipfile.lock",
    JSON.stringify(
      { default: { idna: { version: "==3.4" } }, develop: { pytest: { version: "==7.0.0" } } },
      null,
      2,
    ),
  );
  const scan = (name: string, extra: { includeTests?: boolean; includeDev?: boolean } = {}) =>
    scanProject({
      root,
      out: path.join(temp, name),
      engines: ["builtin"],
      http: client,
      noIgnoreFile: true,
      noBaseline: true,
      formats: ["json"],
      ...extra,
    });

  it("lowers a dev-only advisory to low and leaves runtime ones alone", async () => {
    const result = await scan("devdeps-out");
    const sca = result.findings.filter((finding) => finding.category === "sca");
    const dev = sca.find((finding) => finding.package === "pytest");
    const runtime = sca.find((finding) => finding.package === "idna");
    expect(dev?.dependencyScope).toBe("dev");
    expect(dev?.confidence).toBe("low");
    expect(dev?.confidenceOriginal).toBe("high");
    expect(dev?.adjustments).toEqual(["dev-dependency"]);
    expect(runtime?.dependencyScope).toBe("runtime");
    expect(runtime?.confidence).toBe("high");
    expect(runtime?.adjustments).toBeUndefined();
    // Recorded, but a manifest is not lowered for being under tests/.
    expect(runtime?.pathContext).toBe("test");
    expect((result.run as { adjustments: Record<string, number> }).adjustments).toEqual({
      "dev-dependency": 1,
    });
  });

  it("is switched off by --include-dev and not by --include-tests", async () => {
    const includeTests = await scan("devdeps-out-tests", { includeTests: true });
    const stillLowered = includeTests.findings.find((finding) => finding.package === "pytest");
    expect(stillLowered?.confidence).toBe("low");
    expect(stillLowered?.adjustments).toEqual(["dev-dependency"]);

    const includeDev = await scan("devdeps-out-dev", { includeDev: true });
    const kept = includeDev.findings.find((finding) => finding.package === "pytest");
    expect(kept?.dependencyScope).toBe("dev");
    expect(kept?.confidence).toBe("high");
    expect(kept?.confidenceOriginal).toBeUndefined();
    expect(kept?.adjustments).toBeUndefined();
    expect((includeDev.run as { args: { includeDev: boolean } }).args.includeDev).toBe(true);
  });
});

