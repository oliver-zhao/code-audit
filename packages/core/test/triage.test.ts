describe("CLI flags", () => {
  it("accepts --include-tests and --include-dev and records them", () => {
    const root = path.join(temp, "cli-flags");
    writeFile(root, "tests/test_app.py", PYTHON_APP);
    const scan = (extra: string[], out: string) =>
      spawnSync(
        process.execPath,
        [CLI, "scan", root, "--offline", "--no-external", "--format", "json", "--out", path.join(temp, out), ...extra],
        { cwd: REPO_ROOT, encoding: "utf8", timeout: 60_000 },
      );
    const read = (out: string) => {
      const dir = path.join(temp, out);
      const runId = fs.readdirSync(dir).find((name) => /^\d{8}T/.test(name)) as string;
      return {
        run: JSON.parse(fs.readFileSync(path.join(dir, runId, "run.json"), "utf8")) as {
          args: { includeTests: boolean; includeDev: boolean };
          pathContext: { lowered: number; test: number };
        },
        findings: (
          JSON.parse(fs.readFileSync(path.join(dir, runId, "findings.json"), "utf8")) as { findings: Finding[] }
        ).findings,
      };
    };
    const plain = scan([], "cli-flags-plain");
    expect(plain.status).not.toBe(2);
    const lowered = read("cli-flags-plain");
    expect(lowered.run.args).toMatchObject({ includeTests: false, includeDev: false });
    expect(lowered.run.pathContext.lowered).toBeGreaterThan(0);
    expect(lowered.findings.every((finding) => finding.pathContext === "test")).toBe(true);

    const flagged = scan(["--include-tests", "--include-dev"], "cli-flags-include");
    expect(flagged.status).toBe(1);
    const included = read("cli-flags-include");
    expect(included.run.args).toMatchObject({ includeTests: true, includeDev: true });
    expect(included.run.pathContext.lowered).toBe(0);
    expect(included.run.pathContext.test).toBe(lowered.run.pathContext.test);
    expect(included.findings.length).toBe(lowered.findings.length);
    expect(included.findings.every((finding) => finding.confidenceOriginal === undefined)).toBe(true);
  });
});
